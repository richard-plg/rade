#!/usr/bin/env bash
# Self-test for scripts/trace.sh against the mini roots in scripts/testdata/trace/.
# Check names here never carry an AC ID, so this file never counts as coverage.
# Usage: scripts/trace_test.sh   (exit 1 if any case fails)
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
trace="$here/trace.sh"
fixtures="$here/testdata/trace"
work_base=${TMPDIR:-"$here/../target/tmp"}
mkdir -p "$work_base"
work=$(mktemp -d "$work_base/trace_test.XXXXXX")
trap 'rm -rf "$work"' EXIT

pass=0 fail=0
check() { # name, command...
    local name=$1; shift
    if "$@"; then pass=$((pass + 1)); echo "ok   $name"
    else fail=$((fail + 1)); echo "FAIL $name"; fi
}

# root <fixture> → a fresh copy (the fixtures are never written to)
root() {
    local dst; dst="$work/$1.$RANDOM$RANDOM"
    cp -r "$fixtures/$1" "$dst"
    echo "$dst"
}
# run <root> [args...] → sets out (stdout+stderr) and rc
run() {
    local r=$1; shift
    rc=0; out=$("$trace" --root "$r" "$@" 2>&1) || rc=$?
}
has() { grep -qF -- "$1" <<<"$out"; }
lacks() { ! grep -qF -- "$1" <<<"$out"; }
row() { # root, AC, status → the trace.md row of AC has that status
    grep -E "^\| $2 \|" "$1/docs/checks/trace.md" 2>/dev/null | grep -qF "| $3 |"
}
rowtests() { # root, AC, text → that AC's row mentions text
    grep -E "^\| $2 \|" "$1/docs/checks/trace.md" 2>/dev/null | grep -qF -- "$3"
}

# ── listing and coverage ─────────────────────────────────────────────────────
r=$(root basic); run "$r"
check "basic exits 0 (no gated milestone)" test "$rc" = 0
check "basic summary line" has "ACs: 7 (R97–R98), covered 5, missing 2, format errors 0"
check "basic writes trace.md" test -f "$r/docs/checks/trace.md"
check "rust fn definition counts" row "$r" R97-a covered
check "rust fn location recorded" rowtests "$r" R97-a "crates/x/src/lib.rs:2"
check "e2e check name counts" row "$r" R97-b covered
check "e2e check location recorded" rowtests "$r" R97-b "tests/e2e/mX.sh:2"
check "single-quoted check name counts" row "$r" R97-e covered
check "several ids in one fn name count" row "$r" R97-d covered
check "first of several ids counts" row "$r" R98-b covered
check "comments, strings, longer ids and later args do not count" row "$r" R97-c missing
check "AC without kind is listed as missing" row "$r" R98-a missing
check "kind column filled" rowtests "$r" R97-c "unit+e2e"
check "milestone column filled" rowtests "$r" R98-a "M37"
check "longer id is not a hit" bash -c "! grep -E '^\| R97-c \|' '$r/docs/checks/trace.md' | grep -q 'lib.rs:6'"
check "removed and superseded sections skipped" bash -c "! grep -qE '^\| R(99|100)-' '$r/docs/checks/trace.md'"
check "sections below R97 ignored" bash -c "! grep -qE '^\| R96-' '$r/docs/checks/trace.md'"
check "text outside R sections ignored" bash -c "! grep -qE '^\| R97-z' '$r/docs/checks/trace.md'"
check "rows sorted by R then letter" bash -c "test \"\$(grep -oE '^\| R[0-9]+-[a-z]+' '$r/docs/checks/trace.md' | tr -d '| ' | tr '\n' ' ')\" = 'R97-a R97-b R97-c R97-d R97-e R98-a R98-b '"
check "per-milestone summary present" grep -qE '^\| M36 \| 5 \| 4 \| 1 \| no \|' "$r/docs/checks/trace.md"
check "generated header present" grep -qF "Generated by scripts/trace.sh" "$r/docs/checks/trace.md"

# ── byte-stable rerun ────────────────────────────────────────────────────────
cp "$r/docs/checks/trace.md" "$work/first.md" 2>/dev/null || : >"$work/first.md"
run "$r"
check "rerun is byte-identical" cmp -s "$work/first.md" "$r/docs/checks/trace.md"

# ── --no-write ───────────────────────────────────────────────────────────────
r=$(root basic); run "$r" --no-write
check "no-write exits 0" test "$rc" = 0
check "no-write leaves no file" test ! -e "$r/docs/checks/trace.md"
check "no-write prints the table" has "| R97-a | M36 | unit | covered |"
check "no-write prints the summary" has "ACs: 7 (R97–R98), covered 5, missing 2, format errors 0"

# ── gating ───────────────────────────────────────────────────────────────────
r=$(root basic); mkdir -p "$r/docs/checks"; echo "# M36" >"$r/docs/checks/M36.md"
run "$r" --no-write
check "gated milestone with a missing AC exits 1" test "$rc" = 1
check "gated failure names the AC" has "R97-c"
r=$(root basic); mkdir -p "$r/docs/checks"; echo "# M38" >"$r/docs/checks/M38.md"
run "$r" --no-write
check "gate on a milestone without missing ACs exits 0" test "$rc" = 0
r=$(root basic); run "$r" --no-write --strict
check "strict exits 1 on any missing AC" test "$rc" = 1

# ── no 1.0 sections ──────────────────────────────────────────────────────────
r=$(root empty); run "$r"
check "empty PRD exits 0" test "$rc" = 0
check "empty PRD reports 0 ACs" has "ACs: 0"
check "empty PRD reports 0 format errors" has "format errors 0"
run "$r" --strict
check "empty PRD strict exits 0" test "$rc" = 0

# ── --prd override ───────────────────────────────────────────────────────────
r=$(root empty); run "$r" --no-write --prd "$fixtures/basic/docs/PRD.md"
check "prd override is read" has "ACs: 7 (R97–R98)"

# ── format errors → exit 2 ───────────────────────────────────────────────────
for c in fmt-no-then fmt-order fmt-no-milestone fmt-bad-kind fmt-wrong-section fmt-duplicate fmt-empty-section; do
    r=$(root "$c"); run "$r" --no-write
    check "$c exits 2" test "$rc" = 2
    check "$c counts a format error" bash -c "grep -qE 'format errors [1-9]' <<<\"\$1\"" _ "$out"
done
r=$(root fmt-no-then); run "$r" --no-write
check "format error names file and line" has "docs/PRD.md:2"
r=$(root fmt-duplicate); run "$r"
check "format error writes no trace.md" test ! -e "$r/docs/checks/trace.md"

# ── usage ────────────────────────────────────────────────────────────────────
rc=0; "$trace" --bogus >/dev/null 2>&1 || rc=$?
check "unknown option exits 2" test "$rc" = 2

echo "trace_test: $pass passed, $fail failed"
[[ $fail == 0 ]]
