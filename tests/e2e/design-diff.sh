#!/usr/bin/env bash
# Design diff (build plan §3.5): target/design-diff/index.html shows each
# golden scene's mockup PNG (docs/design/redesign-2026-10-23/new-<s>-<theme>.png)
# beside the GTK screenshot (OUT, default target/e2e-m37/<s>-<theme>.png)
# and the approved golden (GOLDEN, default tests/e2e/golden/m37/), for the
# reviewer who approves a golden. Scenes: SCENES (default "a b c d").
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUT=${OUT:-$ROOT/target/e2e-m37}
GOLDEN=${GOLDEN:-$HERE/golden/m37}
DST=$ROOT/target/design-diff
SCENES=${SCENES:-a b c d}
mkdir -p "$DST/img"
rows=""
for s in $SCENES; do
    for th in dark light; do
        mock=$ROOT/docs/design/redesign-2026-10-23/new-$s-$th.png
        gtk=$OUT/$s-$th.png
        gold=$GOLDEN/$s-$th.png
        cell() { # file, label
            if [[ -s $1 ]]; then
                cp "$1" "$DST/img/$s-$th-$2.png"
                printf '<figure><img src="img/%s" alt="%s"><figcaption>%s</figcaption></figure>' "$s-$th-$2.png" "$2" "$2"
            else
                printf '<figure class="missing"><figcaption>%s: missing (%s)</figcaption></figure>' "$2" "${1#$ROOT/}"
            fi
        }
        rows+="<section><h2>Scene ${s^^} · $th</h2><div class=row>$(cell "$mock" mockup)$(cell "$gtk" gtk)$(cell "$gold" golden)</div></section>"
    done
done
cat > "$DST/index.html" <<HTML
<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Design diff</title>
<style>
:root { color-scheme: dark; --bg: #0d1013; --fg: #e6e9ee; --dim: #8b949e; --line: #23282e; }
body { margin: 0; padding: 16px; background: var(--bg); color: var(--fg); font: 14px/1.4 system-ui, sans-serif; }
h1 { font-size: 18px; } h2 { font-size: 15px; margin: 24px 0 8px; }
.row { display: grid; grid-template-columns: repeat(auto-fit, minmax(320px, 1fr)); gap: 12px; }
figure { margin: 0; border: 1px solid var(--line); border-radius: 6px; padding: 6px; }
img { width: 100%; height: auto; display: block; }
figcaption { color: var(--dim); font-size: 12px; margin-top: 4px; }
.missing { color: var(--dim); }
</style></head><body>
<h1>Design diff — mockup · GTK · approved golden</h1>
<p>Generated by tests/e2e/design-diff.sh on $(date -u +%Y-%m-%dT%H:%MZ). Where the sheet and the mockup differ, the sheet wins (docs/design/spec/README.md).</p>
$rows
</body></html>
HTML
echo "$DST/index.html"
