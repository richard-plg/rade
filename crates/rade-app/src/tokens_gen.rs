//! The design-token generator (PRD R102.1, ADR-0036 §3), shared by `build.rs`
//! (`#[path]`) and the unit tests: `tokens.toml` → the GTK `tokens.css`, the
//! mockup's `tokens.css` and the Rust table behind `crate::tokens`.
//!
//! `tokens.toml` is read line by line (sections `[dark]` / `[light]` with
//! `name = "#rrggbb[aa]"` lines; other sections, such as `[contrast]` for
//! `docs/internals/design/contrast.py`, are skipped), so the token order of the file is
//! kept and no TOML crate is needed at build time.
#![allow(dead_code)]

/// The tokens of one file: `(name, value)` in file order, per theme.
#[derive(Debug, Default, PartialEq)]
pub struct Tokens {
    pub dark: Vec<(String, String)>,
    pub light: Vec<(String, String)>,
}

/// The marker between the light and the dark half of the GTK `tokens.css`.
pub const DARK_MARKER: &str = "/* theme: dark */";

/// Shadow geometry of the shadow tokens (their token value is the color).
pub const SHADOW_GEOMETRY: &[(&str, &str)] = &[
    ("shadow", "0 20px 60px {shadow}"),
    ("glow", "0 0 0 1px {acc-line}, 0 0 18px {glow}"),
];

fn valid_name(n: &str) -> bool {
    !n.is_empty()
        && n.chars().next().is_some_and(|c| c.is_ascii_lowercase())
        && n.chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

fn valid_value(v: &str) -> bool {
    v.strip_prefix('#')
        .is_some_and(|h| (h.len() == 6 || h.len() == 8) && h.chars().all(|c| c.is_ascii_hexdigit()))
}

/// Parse `tokens.toml`. Errors name the line.
pub fn parse(src: &str) -> Result<Tokens, String> {
    let mut t = Tokens::default();
    let mut section = String::new();
    for (i, raw) in src.lines().enumerate() {
        let n = i + 1;
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(s) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
            section = s.trim().to_string();
            continue;
        }
        let list = match section.as_str() {
            "dark" => &mut t.dark,
            "light" => &mut t.light,
            _ => continue,
        };
        let (k, v) = line
            .split_once('=')
            .ok_or_else(|| format!("tokens.toml:{n}: expected name = \"#hex\""))?;
        let (k, v) = (k.trim(), v.trim());
        let v = v
            .strip_prefix('"')
            .and_then(|v| v.strip_suffix('"'))
            .ok_or_else(|| format!("tokens.toml:{n}: value of {k} must be a quoted string"))?;
        if !valid_name(k) {
            return Err(format!("tokens.toml:{n}: bad token name '{k}'"));
        }
        if !valid_value(v) {
            return Err(format!(
                "tokens.toml:{n}: {k} = \"{v}\" is not #rrggbb or #rrggbbaa"
            ));
        }
        if list.iter().any(|(x, _)| x == k) {
            return Err(format!("tokens.toml:{n}: {k} defined twice in [{section}]"));
        }
        list.push((k.to_string(), v.to_ascii_lowercase()));
    }
    let names = |l: &[(String, String)]| l.iter().map(|(k, _)| k.clone()).collect::<Vec<_>>();
    if names(&t.dark) != names(&t.light) {
        return Err(
            "tokens.toml: [dark] and [light] must name the same tokens in the same order".into(),
        );
    }
    if t.dark.is_empty() {
        return Err("tokens.toml: no [dark] tokens".into());
    }
    Ok(t)
}

const HEADER: &str =
    "Generated by crates/rade-app/build.rs from crates/rade-app/src/tokens.toml. Do not edit.";

/// The GTK stylesheet: one `@define-color` per token, the light half first,
/// then [`DARK_MARKER`] and the dark half (loaded while the style is dark).
pub fn gtk_css(t: &Tokens) -> String {
    let mut s = format!("/* {HEADER} */\n/* theme: light */\n");
    for (k, v) in &t.light {
        s += &format!("@define-color {k} {v};\n");
    }
    s += DARK_MARKER;
    s.push('\n');
    for (k, v) in &t.dark {
        s += &format!("@define-color {k} {v};\n");
    }
    s
}

/// `(light, dark)` halves of a [`gtk_css`] text.
pub fn split_gtk_css(css: &str) -> (&str, &str) {
    css.split_once(DARK_MARKER).unwrap_or((css, ""))
}

fn shadow_value(name: &str, list: &[(String, String)]) -> Option<String> {
    let (_, geo) = SHADOW_GEOMETRY.iter().find(|(n, _)| *n == name)?;
    let mut out = geo.to_string();
    for (k, v) in list {
        out = out.replace(&format!("{{{k}}}"), v);
    }
    Some(out)
}

/// The mockup's `tokens.css`: CSS variables for `:root` (dark) and
/// `body.light`, the shadow tokens as full `box-shadow` values.
pub fn mockup_css(t: &Tokens) -> String {
    let block = |sel: &str, list: &[(String, String)]| {
        let mut s = format!("{sel} {{\n");
        for (k, v) in list {
            let v = shadow_value(k, list).unwrap_or_else(|| v.clone());
            s += &format!("  --{k}: {v};\n");
        }
        s + "}\n"
    };
    format!(
        "/* {HEADER} */\n{}{}",
        block(":root", &t.dark),
        block("body.light", &t.light)
    )
}

/// Rust source with `LIGHT` / `DARK` tables, included by `crate::tokens`.
pub fn rust_table(t: &Tokens) -> String {
    let table = |name: &str, list: &[(String, String)]| {
        let mut s = format!("pub const {name}: &[(&str, &str)] = &[\n");
        for (k, v) in list {
            s += &format!("    ({k:?}, {v:?}),\n");
        }
        s + "];\n"
    };
    format!(
        "// {HEADER}\n{}{}",
        table("LIGHT", &t.light),
        table("DARK", &t.dark)
    )
}
