/// One scheme's XML.
pub fn scheme_xml(dark: bool) -> String {
    let t = |name: &str| rgb(name, dark);
    let (id, name) = if dark {
        (DARK, "RADE Dark")
    } else {
        (LIGHT, "RADE Light")
    };
    let mut out = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!-- Generated by RADE from tokens.toml (ADR-0037); colors of GitHub {} Default, MIT. -->\n\
         <style-scheme id=\"{id}\" name=\"{name}\" version=\"1.0\" kind=\"{}\">\n\
         \x20 <style name=\"text\" foreground=\"{}\" background=\"{}\"/>\n\
         \x20 <style name=\"line-numbers\" foreground=\"{}\" background=\"{}\"/>\n\
         \x20 <style name=\"current-line-number\" foreground=\"{}\" background=\"{}\" bold=\"false\"/>\n\
         \x20 <style name=\"current-line\" background=\"{}\"/>\n\
         \x20 <style name=\"selection\" background=\"{}\"/>\n\
         \x20 <style name=\"selection-unfocused\" background=\"{}\"/>\n\
         \x20 <style name=\"cursor\" foreground=\"{}\"/>\n\
         \x20 <style name=\"bracket-match\" background=\"{}\" bold=\"true\"/>\n\
         \x20 <style name=\"search-match\" background=\"{}\"/>\n\
         \x20 <style name=\"right-margin\" foreground=\"{}\" background=\"{}\"/>\n\
         \x20 <style name=\"background-pattern\" background=\"{}\"/>\n",
        if dark { "Dark" } else { "Light" },
        if dark { "dark" } else { "light" },
        t("term-fg"),
        t("bg0"),
        t("fg3"),
        t("bg0"),
        t("fg"),
        t("bg0"),
        t("bg1"),
        t("term-sel"),
        t("bg3"),
        t("acc"),
        t("bg4"),
        t("term-sel"),
        t("bg3"),
        t("bg0"),
        t("bg1"),
    );
    for (style, token, bold, italic) in STYLES {
        out += &format!("  <style name=\"{style}\" foreground=\"{}\"", t(token));
        if *bold {
            out += " bold=\"true\"";
        }
        if *italic {
            out += " italic=\"true\"";
        }
        out += "/>\n";
    }
    out + "</style-scheme>\n"
}

/// Writes both schemes and puts their folder first on the scheme search
/// path; before the first Viewer or Review.
pub fn install() {
    let dir = glib::user_runtime_dir().join("rade").join("styles");
    if std::fs::create_dir_all(&dir).is_err() {
        return;
    }
    for (file, dark) in [("rade-dark.xml", true), ("rade-light.xml", false)] {
        let path = dir.join(file);
        let text = scheme_xml(dark);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            let tmp = dir.join(format!(".{file}.{}", std::process::id()));
            if std::fs::write(&tmp, &text).is_ok() {
                let _ = std::fs::rename(&tmp, &path);
            }
        }
    }
    let m = sourceview5::StyleSchemeManager::default();
    m.prepend_search_path(&dir.to_string_lossy());
    m.force_rescan();
}

