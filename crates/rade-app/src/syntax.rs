/// CSS for Markdown code blocks: the same colors as the Viewer's scheme.
pub fn markdown_css(dark: bool) -> String {
    let mut out = String::from("pre span { color: inherit; background: none !important; font-style: normal; font-weight: inherit; }\n");
    for (selector, token) in SCOPES {
        let scoped: Vec<String> = selector
            .split(", ")
            .map(|s| format!("pre span{s}"))
            .collect();
        out += &format!("{} {{ color: {}; }}\n", scoped.join(", "), rgb(token, dark));
    }
    out += "pre span.markup.bold { font-weight: 600; } pre span.markup.italic, pre span.comment.documentation { font-style: italic; }\n";
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn r112_i_schemes_take_every_color_from_the_tokens() {
        for dark in [false, true] {
            let x = super::scheme_xml(dark);
            assert!(x.contains(&format!(
                "<style name=\"text\" foreground=\"{}\" background=\"{}\"/>",
                crate::tokens::rgb("term-fg", dark),
                crate::tokens::rgb("bg0", dark)
            )));
            assert!(x.contains(&format!(
                "<style name=\"def:keyword\" foreground=\"{}\"/>",
                crate::tokens::rgb("syn-keyword", dark)
            )));
            assert!(x.contains(if dark {
                "id=\"rade-dark\""
            } else {
                "id=\"rade-light\""
            }));
            // Every color in the file is a token's.
            for hex in x.match_indices('#').map(|(i, _)| &x[i..i + 7]) {
                let known = crate::tokens::LIGHT
                    .iter()
                    .chain(crate::tokens::DARK)
                    .any(|(_, v)| v.starts_with(hex));
                assert!(known, "{hex} is a token");
            }
            let css = super::markdown_css(dark);
            assert!(css.contains(&format!(
                "pre span.entity.name.function, pre span.support.function {{ color: {}; }}",
                crate::tokens::rgb("syn-function", dark)
            )));
        }
    }
}
